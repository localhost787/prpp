import {chromium,expect} from '../../../node_modules/@playwright/test/index.mjs';
import {showDemoControls} from './entry-helpers.mjs';
import {mkdir,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
const dir='../../docs/evidence/demo-family-access';await mkdir(dir,{recursive:true});
const browser=await chromium.launch({channel:'chrome',headless:true});
const evidence={mode:'local-synthetic-http',cases:[],errors:[],unexpectedRequests:[]};
try{
 for(const width of [320,390,1280]) for(const lang of ['en','es']){
  const page=await browser.newPage({viewport:{width,height:900},acceptDownloads:true});
  page.on('pageerror',e=>evidence.errors.push(e.message));page.on('console',m=>{if(m.type()==='error')evidence.errors.push(m.text());});
  page.on('request',r=>{if(['fetch','xhr'].includes(r.resourceType())||!r.url().startsWith('http://127.0.0.1:3001/'))evidence.unexpectedRequests.push(r.url());});
  const button=name=>page.getByRole('button',{name,exact:true});
  const select=async(name)=>{await showDemoControls(page);await button(`${lang==='en'?'View':'Vista'} ${name}`).click();};
  const family=()=>button(lang==='en'?'Go to Family':'Ir a Familia').click();
  const results=()=>button(lang==='en'?'Go to Results':'Ir a Resultados');
  const toggle=(label)=>page.getByRole('switch',{name:new RegExp(`^${label}:`)});
  const studies=lang==='en'?'Studies and results':'Estudios y resultados';
  const medicines=lang==='en'?'Medicines':'Medicinas';
  await page.goto('http://127.0.0.1:3001');if(lang==='es')await button('Switch language to Spanish').click();
  await family();await expect(page.getByRole('heading',{name:'Lourdes Santiago Rivera',exact:true})).toBeVisible();
  await expect(toggle(studies)).toHaveAttribute('aria-checked','false');await toggle(studies).click();
  await expect(toggle(studies)).toHaveAttribute('aria-checked','true');
  await toggle(medicines).click();await expect(toggle(medicines)).toHaveAttribute('aria-checked','false');
  await select('Lourdes');
  await expect(page.getByTestId('context-card')).toContainText('Lourdes Santiago Rivera');
  await expect(page.getByTestId('patient-name')).toHaveText('Carmen Rivera Colón');
  await expect(results()).toBeEnabled();await results().click();
  await button(lang==='en'?'View report: Complete blood count':'Ver informe: Hemograma completo').click();
  await expect(page.getByTestId('report-a')).toContainText('15.2');
  const waiting=page.waitForEvent('download');await button(lang==='en'?'Download synthetic PDF: Complete blood count':'Descargar PDF sintético: Hemograma completo').click();
  const download=await waiting;const path=`${dir}/delegate-${width}-${lang}.pdf`;await download.saveAs(path);
  expect(execFileSync('pdftotext',[path,'-'],{encoding:'utf8'})).toContain('15.2');
  await button(lang==='en'?'Go to My care':'Ir a Mi cuidado').click();
  await expect(page.getByTestId('care-panel')).not.toContainText(/ceftriax|acetamin/i);
  await family();await expect(page.getByRole('switch')).toHaveCount(0);
  await page.screenshot({path:`${dir}/delegate-${width}-${lang}.png`,fullPage:true});
  await select('Carmen');await family();
  await expect(toggle(studies)).toHaveAttribute('aria-checked','true');await expect(toggle(medicines)).toHaveAttribute('aria-checked','false');
  await toggle(studies).click();await expect(toggle(studies)).toHaveAttribute('aria-checked','false');
  await select('Lourdes');await expect(results()).toBeDisabled();
  await expect(page.getByTestId('report-group')).toHaveCount(0);
  expect(await page.locator('body').innerText()).not.toMatch(/15\.2|Hemograma|Complete blood count/);
  await select('Carmen');await family();
  await button(`${lang==='en'?'Turn off access in this local example':'Apagar acceso en este ejemplo local'}: Lourdes Santiago Rivera`).click();
  for(const sw of await page.getByRole('switch').all())await expect(sw).toHaveAttribute('aria-checked','false');
  await select('Lourdes');await expect(results()).toBeDisabled();
  await expect(page.getByTestId('visit-current')).toHaveCount(0);
  expect(await page.locator('body').innerText()).not.toMatch(/9:05|8:12|Ana Ramos|Cubicle 12|Cubículo 12/);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  expect(await page.evaluate(async()=>[localStorage.length,sessionStorage.length,(await caches.keys()).length,(await indexedDB.databases()).length])).toEqual([0,0,0,0]);
  await page.reload();await button('Go to Family').click();
  await expect(toggle('Studies and results')).toHaveAttribute('aria-checked','false');
  await expect(toggle('Medicines')).toHaveAttribute('aria-checked','true');
  evidence.cases.push({width,lang,grant:true,download:true,revoke:true,ownerPersistence:true,reloadReset:true});await page.close();
 }
 expect(evidence.errors).toEqual([]);expect(evidence.unexpectedRequests).toEqual([]);
}finally{await browser.close();await writeFile(`${dir}/browser.json`,JSON.stringify(evidence,null,2));}
console.log(JSON.stringify(evidence));
