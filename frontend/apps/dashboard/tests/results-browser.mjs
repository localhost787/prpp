import { enterContext, changeRole } from './entry-helpers.mjs';
import { chromium, expect } from '../../../node_modules/@playwright/test/index.mjs';
import { mkdir, writeFile } from 'node:fs/promises';
const folder = '../../docs/evidence/AYO-78';
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const report = { browser: browser.version(), mode: 'synthetic-local', cases: [] };
try {
 for (const width of [320, 390, 1280]) {
  const context = await browser.newContext({ viewport: { width, height: 900 } });
  const page = await context.newPage(); const errors = [], requests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('console', msg => { if (msg.type() === 'error') errors.push(msg.text()); });
  page.on('request', request => { if (['fetch', 'xhr'].includes(request.resourceType()) || !request.url().startsWith('http://127.0.0.1:3001/')) requests.push(request.url()); });
  await page.goto('http://127.0.0.1:3001');
    await expect(page.locator('html')).toHaveAttribute('lang', 'es');
  await enterContext(page, 'Carmen', 'self', 'es');
  await page.getByRole('button', { name: 'Abrir Resultados', exact: true }).click();
  await expect(page.getByTestId('section-heading')).toBeFocused();
  await expect(page.getByTestId('result-card')).toHaveCount(6);
  await page.getByRole('textbox', { name: 'Buscar resultado' }).fill('sin coincidencia');
  await expect(page.getByText('No hay coincidencias con este filtro. No significa que no haya resultados.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Quitar filtro', exact: true }).click();
  await expect(page.getByTestId('result-card')).toHaveCount(6);
  await expect(page.getByTestId('results-panel').getByText('Pendiente de implementación', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Ver detalle: Glóbulos blancos', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Cerrar detalle: Glóbulos blancos', exact: true })).toBeFocused();
  await expect(page.getByText('Están altos. Suele pasar cuando el cuerpo combate una infección.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Cerrar detalle: Glóbulos blancos', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Ver detalle: Glóbulos blancos', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Filtrar: Preliminar', exact: true }).click();
  await expect(page.getByTestId('result-card')).toHaveCount(1);
  await page.getByRole('button', { name: 'Ver detalle: Radiografía de tórax', exact: true }).click();
  await expect(page.getByText('Hay un primer resultado. Puede cambiar cuando lo confirmen.', { exact: true })).toBeVisible();
  await expect(page.getByTestId('result-card').getByText('Sin interpretación', { exact: true })).toBeVisible();
  await page.getByTestId('results-panel').scrollIntoViewIfNeeded();
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${folder}/preliminar-${width}.png`, fullPage: true });
  await page.getByRole('button', { name: 'Filtrar: Todos', exact: true }).click();
  await expect(page.getByTestId('result-card')).toHaveCount(6);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: `${folder}/resultados-${width}.png`, fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  const controls = await page.getByTestId('results-panel').getByRole('button').evaluateAll(nodes => nodes.map(el => ({ width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height })));
  expect(controls.every(c => c.width >= 44 && c.height >= 44)).toBe(true);
  await page.getByRole('button', { name: 'Aumentar letra', exact: true }).click();
  await page.getByRole('button', { name: 'Aumentar letra', exact: true }).click();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(width);
  await enterContext(page, 'Lourdes', 'delegate', 'es');
  await expect(page.getByRole('button', { name: 'Ir a Resultados', exact: true })).toBeDisabled();
  await expect(page.getByTestId('result-card')).toHaveCount(0);
  expect(await page.locator('body').innerText()).not.toMatch(/15\.2|Glóbulos blancos|Hemoglobina|6 resultados/);
  await changeRole(page, 'self', 'es');
  await page.getByRole('button', { name: 'Abrir Resultados', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Buscar resultado' })).toHaveValue('');
  await expect(page.getByTestId('result-card')).toHaveCount(6);
  await page.getByRole('button', { name: 'Filtrar: Listo', exact: true }).click();
  await expect(page.getByTestId('result-card')).toHaveCount(2);
  await page.getByRole('button', { name: 'Vista Lourdes', exact: true }).click();
  await expect(page.getByTestId('result-card')).toHaveCount(0);
  await enterContext(page, 'Carmen', 'self', 'es');
  await page.getByRole('button', { name: 'Abrir Resultados', exact: true }).click();
  await expect(page.getByTestId('result-card')).toHaveCount(6);
  expect(page.url()).toBe('http://127.0.0.1:3001/');
  expect(await page.evaluate(() => [localStorage.length, sessionStorage.length])).toEqual([0, 0]);
  expect(errors).toEqual([]); expect(requests).toEqual([]);
  report.cases.push({ width, passed: true, controls, errors, requests });
  await context.close();
 }
} finally { await writeFile(`${folder}/browser.json`, JSON.stringify(report, null, 2)); await browser.close(); }
